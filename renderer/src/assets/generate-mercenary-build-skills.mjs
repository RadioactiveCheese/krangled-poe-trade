import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const POEDB_URL = 'https://poedb.tw/us/Mercenaries'
const TRADE_ITEMS_URL = 'https://www.pathofexile.com/api/trade/data/items'
const TRADE_STATS_URL = 'https://www.pathofexile.com/api/trade/data/stats'
const OUTPUT_PATH = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  'data',
  'mercenary-build-skills.ts'
)

const headers = { 'User-Agent': 'Krangled-PoE-Trade data generator' }

const [poedbResponse, itemsResponse, statsResponse] = await Promise.all([
  fetch(POEDB_URL, { headers }),
  fetch(TRADE_ITEMS_URL, { headers }),
  fetch(TRADE_STATS_URL, { headers })
])

if (!poedbResponse.ok || !itemsResponse.ok || !statsResponse.ok) {
  throw new Error(`HTTP ${poedbResponse.status}/${itemsResponse.status}/${statsResponse.status}`)
}

const [poedbHtml, items, stats] = await Promise.all([
  poedbResponse.text(),
  itemsResponse.json(),
  statsResponse.json()
])

const poedbBuilds = parsePoedbBuilds(poedbHtml)
const tradeBuilds = items.result
  .flatMap(group => group.entries ?? [])
  .filter(entry => entry.disc === 'mercenary_warrant')
  .map(entry => ({
    name: extractBuildName(entry.text),
    tradeId: entry.type
  }))

const mercenaryStats = stats.result.find(group => group.id === 'mercenary')?.entries ?? []
const skillIdsByName = new Map()
for (const entry of mercenaryStats) {
  if (!entry.id.includes('.skill_')) continue
  if (skillIdsByName.has(entry.text)) {
    throw new Error(`Duplicate official Mercenary skill label: ${entry.text}`)
  }
  skillIdsByName.set(entry.text, entry.id)
}

const generated = {}
for (const build of tradeBuilds) {
  const poedbBuild = poedbBuilds.get(build.name)
  if (!poedbBuild) throw new Error(`PoEDB is missing official build: ${build.name}`)

  generated[build.tradeId] = Object.fromEntries(
    ['primary', 'secondary', 'utility'].map(kind => [
      kind,
      poedbBuild[kind]
        .filter(name => name !== '[DNT] Unused')
        .map(name => {
          const skillId = skillIdsByName.get(name)
          if (!skillId) throw new Error(`Official trade data is missing skill: ${name}`)
          return skillId
        })
    ])
  )
}

const referencedSkillIds = new Set(
  Object.values(generated)
    .flatMap(groups => Object.values(groups))
    .flat()
)
const officialSkillIds = new Set(skillIdsByName.values())
const unreferencedSkillIds = [...officialSkillIds].filter(id => !referencedSkillIds.has(id))

if (tradeBuilds.length !== 63 || Object.keys(generated).length !== tradeBuilds.length) {
  throw new Error(`Expected 63 mapped builds, got ${Object.keys(generated).length}/${tradeBuilds.length}`)
}
if (skillIdsByName.size !== 268 || unreferencedSkillIds.length) {
  throw new Error(`Expected all 268 skills to be referenced; got ${skillIdsByName.size}, missing ${unreferencedSkillIds.join(', ')}`)
}

const records = Object.entries(generated).map(([buildId, groups]) => {
  if (!/^[$A-Z_a-z][$\w]*$/u.test(buildId)) {
    throw new Error(`Build ID is not a valid TypeScript property: ${buildId}`)
  }
  return [
    `  ${buildId}: {`,
    `    primary: [${groups.primary.map(quote).join(', ')}],`,
    `    secondary: [${groups.secondary.map(quote).join(', ')}],`,
    `    utility: [${groups.utility.map(quote).join(', ')}]`,
    '  }'
  ].join('\n')
})

const output = [
  '// Generated by ../generate-mercenary-build-skills.mjs. Do not edit manually.',
  `// Relationships: ${POEDB_URL}`,
  '// Build and skill IDs: official Path of Exile trade metadata.',
  '',
  'export interface MercenaryBuildSkillIds {',
  '  primary: string[]',
  '  secondary: string[]',
  '  utility: string[]',
  '}',
  '',
  'export const MERCENARY_BUILD_SKILL_IDS: Readonly<Record<string, MercenaryBuildSkillIds>> = {',
  records.join(',\n'),
  '}'
].join('\n') + '\n'

await fs.writeFile(OUTPUT_PATH, output)
console.log(`Wrote ${Object.keys(generated).length} builds and ${referencedSkillIds.size} skills to ${OUTPUT_PATH}`)

function parsePoedbBuilds (html) {
  const builds = new Map()
  const marker = '<div class="col"><div class="d-flex border-top rounded">'
  for (const block of html.split(marker).slice(1)) {
    const buildMatch = block.match(/<strong><a href="[^"]+">([^<]+)<\/a><\/strong>/u)
    if (!buildMatch) continue

    const groups = { primary: [], secondary: [], utility: [] }
    const skillPattern = /<div class="col MercenarySkill(Primary|Secondary|Utility)">.*?<\/span>\s*<span[^>]*>([^<]+)<\/span><\/div>/gsu
    for (const match of block.matchAll(skillPattern)) {
      const kind = match[1].toLowerCase()
      const name = decodeHtml(match[2].trim())
      if (!groups[kind].includes(name)) groups[kind].push(name)
    }
    if (Object.values(groups).some(group => group.length)) {
      builds.set(decodeHtml(buildMatch[1].trim()), groups)
    }
  }
  return builds
}

function extractBuildName (text) {
  return text.match(/\(([^()]*)\)$/u)?.[1].trim()
}

function decodeHtml (text) {
  return text
    .replaceAll('&amp;', '&')
    .replaceAll('&quot;', '"')
    .replaceAll('&#39;', "'")
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replace(/&#(\d+);/gu, (_, value) => String.fromCodePoint(Number(value)))
}

function quote (text) {
  const apostrophe = String.fromCharCode(39)
  return apostrophe +
    text.replaceAll('\\', '\\\\').replaceAll(apostrophe, `\\${apostrophe}`) +
    apostrophe
}
